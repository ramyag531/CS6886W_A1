def build_optimizer(model, optimizer_name, lr):
  name = optimizer_name.lower()

  if name == "adam":
      return optim.Adam(model.parameters(), lr=lr)
  elif name == "sgd":
      return optim.SGD(model.parameters(), lr=lr, momentum=0.9)
  elif name == "nesterov":
      return optim.SGD(model.parameters(), lr=lr, momentum=0.9, nesterov=True)
  elif name == "adagrad":
      return optim.Adagrad(model.parameters(), lr=lr)
  elif name == "rmsprop":
      return optim.RMSprop(model.parameters(), lr=lr, momentum=0.9)
  elif name == "nadam":
      return optim.NAdam(model.parameters(), lr=lr)
  else:
      raise NotImplementedError("Optimizer {} not implemented".format(name))

